## Unang Markahan: Heograpiya ng Pilipinas
- **Nilalaman:** Ganap at kaugnay na lokasyon (absolute/relative location) ng Pilipinas sa mundo at sa Timog-Silangang Asya; batayan ng pambansang teritoryo (kapuluan, karagatang teritoryal); heyograpiyang pisikal (kabundukan, ilog, katubigan) at heyograpiyang pantao (populasyon, pamamahagi ng mamamayan).
