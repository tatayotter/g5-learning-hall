## Unang Markahan (uri ng teksto: alamat/pabula/parabula/anekdota; kasanayan: pag-iisa/paglalarawan)
- **Pakikinig at Pagbasa:** Pakikinig at pagbasa ng alamat, pabula, parabula, at anekdota; pagtukoy ng paksa at mga detalyeng naglalarawan dito; pagbasa nang may wastong bilis, kawastuhan, at ekspresyon.
- **Pagsasalita at Pagsulat:** Muling pagsasalaysay ng alamat o pabula gamit ang sariling mga salita; pagsulat ng talatang naglalarawan (deskriptibo) tungkol sa isang tauhan, lugar, o pangyayari sa binasang kuwento.
- **Panonood at Presentasyon:** Panonood at pagsusuri ng larawan o ilustrasyon na kaugnay ng alamat o pabula; pagbibigay-kahulugan sa mensahe ng ilustrasyon.
- **Gramatika:** Unlapi, gitlapi, at hulapi (mag-, nag-, -um-, -in, -an); wastong paggamit ng mga ito sa pagbuo ng pangungusap.

**Special Science enrichment:** hindi inilalapat sa asignaturang Filipino.

## Ikalawang Markahan (uri ng teksto: anekdota/tulang pambata/kuwentong-bayan; kasanayan: recount — talaarawan/talambuhay ng sarili)
