- **Pagsasalita at Pagsulat:** Pagsulat ng sariling talaarawan (personal na karanasan sa loob ng isang araw o linggo); pagsulat ng maikling talambuhay ng sarili, kasama ang mahahalagang detalye tungkol sa sariling buhay.
- **Panonood at Presentasyon:** Pagsasalaysay nang pasalita ng isang personal na karanasan gamit ang tamang pagkakasunod-sunod at ekspresyon.
- **Gramatika:** Pangngalan, panghalip, at pang-uri — mga kayarian (payak, maylapi, tambalan, inuulit); wastong paggamit sa pagsulat ng talaarawan.

