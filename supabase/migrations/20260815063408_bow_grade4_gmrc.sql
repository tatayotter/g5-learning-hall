## Unang Markahan: Paghubog sa Sariling Kamalayan Tungo sa mga Mabuting Gawi
- **Nilalaman:** Pagkilala sa sariling kakayahan, damdamin, at pananagutan bilang batayan ng mabuting pag-uugali; pag-unawa sa kahalagahan ng disiplina sa sarili sa pag-aaral at sa pang-araw-araw na gawain.
- **Kasanayang Pampagkatuto:** (a) Pagtukoy sa sariling lakas at kahinaan at kung paano ito mapauunlad; (b) Pagpapakita ng disiplina sa sarili sa paggamit ng oras, pananalapi, at gamit; (c) Pagsasanay ng pananagutan sa sariling mga pasya at kilos.
- **Pamantayan sa Pagganap:** Naipamamalas ang disiplina sa sarili at pananagutan sa pang-araw-araw na gawain sa tahanan at paaralan.
- **Lilinanging Pagpapahalaga:** Pagpapahalaga sa sarili.

## Ikalawang Markahan: Pamilya Bilang Gabay sa Pagpapaunlad ng mga Mabuting Gawi
- **Nilalaman:** Papel ng bawat miyembro ng pamilya sa pagpapaunlad ng disiplina at mabuting asal; kahalagahan ng katapatan at tiwala sa loob ng tahanan.
- **Kasanayang Pampagkatuto:** (a) Pagtukoy sa tungkulin ng bawat miyembro ng pamilya sa pagpapalago ng mabuting asal; (b) Pagpapakita ng katapatan sa pananalita at kilos sa loob ng pamilya; (c) Paglutas ng maliliit na hidwaan sa pamilya sa mapayapang paraan.
- **Pamantayan sa Pagganap:** Naipamamalas ang katapatan at pakikiisa sa mga tuntunin at gawain ng pamilya.
- **Lilinanging Pagpapahalaga:** Matapat.

## Ikatlong Markahan: Paghubog ng mga Mabuting Gawi Kasama at Para sa Kapuwa
- **Nilalaman:** Paggalang at pakikiramay sa kapwa, kabilang ang mga taong may kapansanan at ibang pangkat sa lipunan; kahalagahan ng pakikipagkapwa-tao sa paaralan at komunidad.
- **Kasanayang Pampagkatuto:** (a) Pagpapakita ng paggalang sa pagkakaiba-iba ng kapwa; (b) Pagtulong at pakikiramay sa kapwa-mag-aaral na nangangailangan; (c) Pakikilahok sa mga gawaing nagtataguyod ng pagkakaisa sa paaralan.
- **Pamantayan sa Pagganap:** Naipamamalas ang paggalang at malasakit sa kapwa sa iba't ibang sitwasyon.
