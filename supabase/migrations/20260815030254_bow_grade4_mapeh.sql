  $bow$# Grade 4 MAPEH — Budget of Work

MAPEH combines four components — Music, Arts, Physical Education, and Health — each covered across the school year, often paced roughly one component focus per quarter while weaving in the others through integrated activities.

## Term 1: Music and Arts Foundations
- **Music:** Identifying and clapping simple rhythmic patterns (whole, half, quarter notes) in Philippine folk songs; singing familiar folk songs from one's own region with correct pitch and rhythm; describing basic music elements (beat, tempo, dynamics — loud/soft).
- **Arts:** Identifying basic visual art elements (line, shape, color, texture) in artworks and everyday objects; creating a simple artwork (drawing, coloring, or paper craft) using at least two of these elements; discussing simple traditional Filipino crafts (weaving, pottery) found in the community.
- **Integration:** Connecting a regional folk song to a related visual art motif (e.g., illustrating the story of a folk song) for a small term output.

## Term 2: Physical Education Foundations
- **PE:** Practicing locomotor movements (running, jumping, skipping) and non-locomotor movements (bending, twisting, balancing) with proper form; participating in simple games and Philippine traditional games (Laro ng Lahi) that build coordination and teamwork.
- **Fitness:** Performing basic warm-up and stretching routines before physical activity; describing why regular physical activity is important for a healthy body.
- **Integration:** Combining a Laro ng Lahi game with a simple musical rhythm or chant learned in Term 1 for a class activity.

## Term 3: Health and Wellness
- **Health:** Describing habits of personal hygiene and cleanliness (handwashing, dental care, proper grooming) and their role in preventing illness; identifying the food groups and describing a balanced meal appropriate for one's age.
- **Safety:** Identifying common hazards at home, school, and in the community, and the correct response to simple emergencies (fire, minor injury); describing ways to stay safe near roads, water, and electrical appliances.
- **Integration:** Planning a simple balanced-meal chart or a short health-and-safety poster combining Health content with Arts skills from Term 1.

## Term 4: Music, Arts, PE, and Health Integration
- **Music and Arts:** Composing a simple rhythmic pattern or short verse and pairing it with a related drawing or craft, showing growth from Term 1 skills.
- **PE and Health:** Demonstrating improved control in locomotor/non-locomotor movement sequences; explaining how physical activity, hygiene, and balanced nutrition work together to support overall wellness.
- **Year-end project:** Creating a small multi-component output (e.g., a short performance combining a folk song, a simple dance or movement sequence, and a health message) that draws on all four MAPEH components learned across the year.

