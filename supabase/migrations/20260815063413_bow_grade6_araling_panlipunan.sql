- **Nilalaman:** Lokasyon, kontinente, at karagatan ng daigdig; mga pangunahing anyong-lupa at anyong-tubig sa iba't ibang bahagi ng mundo; epekto ng heograpiya sa pamumuhay ng iba't ibang bansa.
