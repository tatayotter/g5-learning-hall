CREATE INDEX IF NOT EXISTS idx_weekly_packages_user
  ON public.weekly_packages USING btree (user_id, week_starting_date);

ALTER TABLE public.weekly_packages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "weekly_packages: read all" ON public.weekly_packages;
