CREATE TABLE IF NOT EXISTS public.weekly_packages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL DEFAULT 'damien',
  week_starting_date date NOT NULL,
  package_data jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  quiz_attempts jsonb DEFAULT '{}'::jsonb,
  character_stats jsonb DEFAULT '{"xp": 0, "gold": 0, "level": 1}'::jsonb,
  mastered_quizzes jsonb DEFAULT '[]'::jsonb,
  journal_logs jsonb DEFAULT '{}'::jsonb,
  mastery_count integer DEFAULT 0,
  purchased_items integer DEFAULT 0,
  honor_grants integer DEFAULT 0,
  achievements jsonb DEFAULT '{}'::jsonb,
  guild_sessions_count integer DEFAULT 0,
  monster_battles_won integer DEFAULT 0,
  sibling_battles_won integer DEFAULT 0,
  perfect_quizzes integer DEFAULT 0,
  dummy_battles_won integer DEFAULT 0,
  eggs_hatched integer DEFAULT 0,
  curios_graduated integer DEFAULT 0,
  trades_completed integer DEFAULT 0,
  legendaries_caught integer DEFAULT 0,
  tutor_rerolls integer DEFAULT 0,
  tatay_battles_won integer DEFAULT 0,
  tatay_battles_lost integer DEFAULT 0,
  CONSTRAINT weekly_packages_user_week_unique UNIQUE (user_id, week_starting_date)
