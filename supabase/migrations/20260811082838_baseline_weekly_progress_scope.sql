-- Baseline documentation migration: weekly progress tracking scope only.
--
-- Context: this repo's local supabase/migrations/ was missing ~138 migrations that already
-- exist live (only the boss_fight_schema migration was tracked). Reconciling the FULL history
-- requires `supabase db pull`/`db dump`, which needs Docker Desktop; that was blocked on this
-- machine by a BIOS-level virtualization setting. As a fallback, this migration hand-documents
-- (via SQL introspection against the live project) only the objects touched by the
-- weekly-progress redesign (see docs/weekly-progress-redesign-plan.md) so at least this scope
-- has an accurate, version-controlled record before Phase 1 adds new tables alongside it.
--
-- All objects below already exist in production as of 2026-08-11 — every statement is written
-- idempotently (IF NOT EXISTS / CREATE OR REPLACE / DROP+CREATE POLICY) so applying this is a
-- no-op against the live database. It exists for historical accuracy and future local dev
-- bootstrapping, not to change anything.
--
-- The other ~135 migrations outside this scope remain undocumented locally. That gap is tracked
-- as a known follow-up, not resolved here.

