  $bow$# Grade 4 EPP (AFA/FCS/IA) — Budget of Work

Grade 4 EPP rotates through four strands. Quarter I (ICT) is tracked in the EPP (ICT) entry. Quarters II–IV are below.

## Term 2 — Quarter II: Agriculture and Fishery Arts (AFA)

**Content Standard:** Naipamamalas ang pag-unawa sa natural na pamamaraan nang pagtatanim, pangangalaga, pagpaparami, pag-aani, at pagbebenta ng halamang ornamental, gulay, at punong-prutas.

**Performance Standard:** Ang mga mag-aaral ay naisasagawa ang natural na pamamaraan nang pagtatanim, pangangalaga, pagpaparami, pag-aani, at pagbebenta ng halamang ornamental, halamang-gulay, at punong-prutas.

Content and Learning Competencies:

**Agrikultura, mga sangay nito sa paghahalaman, at pamamaraan ng pagtatanim:**
Content: Kahulugan ng Agrikultura; mga sangay ng Agrikultura sa paghahalaman (agronomy, horticulture, forestry); pamamaraan ng pagtatanim ng halaman (natural vs. organikong pagtatanim, intercropping, contour farming, multiple cropping); alternatibong paraan ng paghahalaman (urban gardening, containerized, vertical gardening, dish gardening, hydroponics, aquaponics, aeroponics).
1. Natatalakay ang kahulugan ng agrikultura at mga sangay nito sa paghahalaman.
2. Natatalakay ang mga pamamaraan ng pagtatanim ng halaman.
3. Nakikilala ang iba't-ibang alternatibong paraan ng paghahalaman.

**Kahalagahan ng Paghahalaman:**
Content: Kahalagahan at kabutihang-dulot ng paghahalaman sa tao (stress reliever, medicinal value, napagkakakitaan, nagbibigay ng sariwang hangin/tubig/pagkain); sa hayop (sariwang hangin, tubig, pagkain); sa kalikasan o kapaligiran (nakapipigil sa baha at pagguho ng lupa, naiiwasan ang polusyon, nagbibigay ng lilim at sariwang hangin, nagpapaganda ng kapaligiran).
4. Natatalakay ang mga kahalagahan at kabutihang dulot ng paghahalaman sa tao, hayop, at kalikasan o kapaligiran.

**Mga batas, lokal na ordinansa, ahensya ng gobyerno at NGOs:**
Content: Mga piling batas (National Law-RA 10068, Organic Agriculture Act of 2010, Ecological Solid Waste Management Act, local ordinances); mga ahensiya (DA, DENR, DTI, DOLE, DOST, TESDA); mga NGO (FAO, MASIPAG, AgriCOOPh).
5. Natatalakay ang mga batas, lokal na ordinansa, ahensya ng gobyerno at mga NGOs at serbisyong kanilang naibibigay ukol sa paghahalaman.

**Mga taong matagumpay sa paghahalaman:**
Content: Mga kilalang magsasaka at entrepreneur sa paghahalaman sa Pilipinas; mga katangian na taglay (masipag, maparaan, masigasig, matiyaga, may dedikasyon, malakas ang loob, may kakayahan sa pagpapalano).
6. Nakikilala ang mga taong naging matagumpay sa paghahalaman sa komunidad at ang mga katangiang kanilang taglay.

**Compost, organikong pataba at natural na pestisidyo:**
Content: Paggawa ng compost (paraan, mga nilalaman, katangian ng magandang compost, vermicomposting); organic concoctions and extracts (FFJ, FPJ, FAA, BOKASHI); natural pestisidyo (OHN 1: white vinegar, bawang, molasses; OHN 2: luya, sibuyas, bawang, molasses, sili; Neem tree oil).
7. Nakagagawa ng compost, organikong pataba, at natural na pestisidyo na magagamit sa paghahanda ng lupa at pangangalaga ng mga pananim.

**Mga salik na dapat isaalang-alang sa paghahalaman:**
Content: Mga panuntunang pangkaligtasan at pangkalusugan sa paghahalaman; kagamitan at kasangkapan at paraan ng pag-iingat; mga salik (lugar, uri ng lupa, uri ng halamang itatanim, partial shade/full sun, suplay ng tubig, pataba, panahon/kalendaryo ng pagtatanim, pagtatala ng gastos).
8. Natatalakay ang mga salik na dapat isaalang-alang sa paghahalaman.

**Pagtatanim ng halaman sa natural na pamamaraan:**
Content: Pagpili ng halamang maaaring itanim (halamang ornamental — san francisco, bougainvillea, cactus, rose, santan; halamang-gulay — talong, kamatis, sili, kalabasa, kamote, kangkong, okra, pipino, pechay; punong-prutas — manga, santol, rambutan); paraan ng pagtatanim (tuwiran at di-tuwiran); paggamit ng mga kagamitan at kasangkapan; mga hakbang sa pagtatanim (gumawa ng plano/layout, suriin at linisin ang lugar, bungkalin ang lupa, haluan ng organikong pataba, patagin gamit ang kalaykay, simulan ang pagtatanim, diligan).
9. Naisasagawa ang pagtatanim ng piniling halaman sa natural na pamamaraan nang may pag-iingat.

**Pangangalaga ng mga pananim:**
Content: Pagdidilig, pagbubungkal, paglalagay ng pataba, pagsugpo sa insekto/sakit/peste, pagsubaybay ng paglaki, pagbubunot ng damo, pagpapausok, paggamit ng baking soda/bawang/sili atbp.
10. Naipakikita ang mga paraan ng pangangalaga ng mga pananim (pre-care, during, post-care).

**Pagpaparami ng halaman:**
Content: Sekswal at asekswal na paraan ng pagpaparami ng halaman.
11. Naipakikita ang pagpaparami ng halaman sa paraang sekswal at asekswal.

**Pag-aani, pag-iimbak at pangangalaga ng inaning tanim:**
Content: Mga palatandaan/indikasyon na dapat isaalang-alang sa pag-aani; mga paraan ng pag-aani; iba't ibang paraan ng pag-iimbak at pangangalaga.
12. Natutukoy ang mga palatandaan o indikasyon na dapat isaalang-alang sa pag-aani.
13. Naipakikita ang mga paraan ng pag-aani.
14. Naisasagawa ang mga paraan ng pag-aani, pag-iimbak, at pangangalaga ng inaning tanim.

**Pagbebenta ng mga inaning tanim:**
Content: Mga paraang maaaring gamitin sa pagbebenta (online at tradisyunal); pagbebenta sa paraang pakyawan, tingian, por kilo, tali, naka-paso at iba pa; pagtutuos ng kinita at tubo gamit ang manwal na pagkukwenta o electronic spreadsheet tool.
15. Naisasagawa nang wasto ang pagbebenta ng mga inani.
16. Naisasagawa ang pagtutuos ng kinita at tubo gamit ang manwal na pagkukwenta o electronic spreadsheet tool.

## Term 3 — Quarter III: Family and Consumer Science (FCS)

**Tungkulin sa Sarili**
Content Standard: Naipamamalas ang pag-unawa sa kahalagahan ng pag-aayos, pangangalaga sa sarili, angkop na pagkilos at pananamit sa panahon ng pagdadalaga at pagbibinata.
Performance Standard: Ang mga mag-aaral ay naipapakita ang pag-aayos, pangangalaga sa sarili, angkop na pagkilos, at pananamit sa panahon ng pagdadalaga at pagbibinata.
Content: Kahalagahan ng pag-aayos at pangangalaga sa sarili; angkop na pagkilos sa panahon ng pagdadalaga at pagbibinata; angkop na pananamit.
Learning Competencies:
1. Natutukoy ang mga pagbabagong pisikal sa sarili.
2. Naipaliliwanag ang mga kagamitan at consumables at gamit nito sa pangangalaga ng sarili.
3. Naisasagawa ang mga paraan sa pag-aayos at pangangalaga ng sarili.
4. Naipakikita ang tamang pagkilos sa panahon ng pagdadalaga at pagbibinata.
5. Nakapipili ng angkop na pananamit sa panahon ng pagdadalaga at pagbibinata.

**Tungkuling Pantahanan**
Content Standard: Naipamamalas ang pag-unawa sa mga tungkuling pantahanan.
Performance Standard: Ang mga mag-aaral ay naisasagawa ang mga gawaing pantahanan nang may pag-iingat.
Content: Kagamitan sa pagsasaing (conventional at makabagong pamamaraan); mga hakbang sa pagsasaing; mga panukalang pangkaligtasan at pangkalusugan; kagamitan at consumable sa paghuhugas ng pinaglutuan at pinagkainan; mga hakbang sa paghuhugas; kagamitan at consumable sa paglilinis ng tahanan; pagliligpit ng mga kagamitan at consumables; mga hakbang sa paglilinis ng silid-tulugan, sala, kusina at bakuran; kagamitan at consumables sa paglalaba (conventional at makabagong pamamaraan); mga hakbang sa paglalaba; kagamitan sa pamamalantsa (conventional at makabagong pamamaraan); mga hakbang sa pamamalantsa.
Learning Competencies:
6. Natutukoy ang mga kagamitan sa pagsasaing ng bigas (conventional at makabagong pamamaraan).
7. Naisasagawa ang mga hakbang sa pagsasaing nang may pag-iingat.
8. Natutukoy ang mga kagamitan at consumable sa paghuhugas ng pinaglutuan at pinagkainan.
9. Naisasagawa ang mga hakbang sa paghuhugas ng pinaglutuan at pinagkainan nang may pag-iingat.
10. Natutukoy ang mga kagamitan at consumable sa paglilinis ng tahanan.
11. Naipaliliwanag ang mga pamamaraan ng pagliligpit ng mga kagamitan at consumable nang may pag-iingat.
12. Naisasagawa ang mga hakbang sa paglilinis ng tahanan at iba pang bahagi nito nang may pag-iingat.
13. Natutukoy ang mga kagamitan at consumables sa paglalaba (conventional at makabagong pamamaraan).
14. Naisasagawa ang mga hakbang sa paglalaba nang may pag-iingat.
15. Natutukoy ang kagamitan sa pamamalantsa (conventional at makabagong pamamaraan).
16. Naisasagawa ang mga hakbang sa pamamalantsa nang may pag-iingat at gabay ng nakatatanda.

## Term 4 — Quarter IV: Industrial Arts (IA)

**Content Standards:** Naipamamalas ang mga kaalaman sa mga kasangkapan at materyales sa pagguhit; naipamamalas ang mga kaalaman sa mga kasangkapan at materyales sa pagbuo ng proyekto mula sa recyclable materials; naipamamalas ang kaalaman sa pagsusukat; naipamamalas ang pang-unawa sa basic sketching, outlining, and shading; naipamamalas ang pang-unawa sa pagsulat ng letra gamit ang mga lettering styles at pagguhit ng alphabet of lines; naipamamalas ang pang-unawa sa orthographic at isometric drawing; naipamamalas ang pang-unawa sa pagre-recycle at pagtutuos ng nabuong proyekto.

**Performance Standards:** Ang mga mag-aaral ay naisasagawa ang pagguhit ng free-hand drawing, orthographic, at isometric drawing; nakagagawa ng proyekto mula sa recyclable materials na maaring pagkakitaan.

Content and Learning Competencies:

**Kasangkapan at materyales sa pagguhit:**
1. Nakikilala ang mga kasangkapan at materyales sa pagguhit.

**Kasangkapan at materyales sa pagbuo ng proyekto mula sa recyclable materials:**
Content: Panukat, panggupit, pambutas, pangkulay, pandikit.
2. Nakikilala ang mga kasangkapan at materyales sa pagbuo ng proyekto.

**System of Measurement:**
Content: Dalawang sistema ng pagsukat (English at Metric System); pagbasa ng gradwasyon; unit conversion (English sa metric at metric sa English).
3. Naisasagawa ang kasanayan sa pagsusukat.

**Free-hand Drawing:**
Content: Basic sketching techniques; outlining; shading.
4. Naisasagawa ang hakbang sa pagguhit ng larawan gamit ang basic sketching, outlining, and shading.

**Lettering Styles:**
Content: Iba't ibang lettering styles; hakbang sa pagsulat ng iba't ibang lettering styles.
5. Naisusulat ang mga letra gamit ang lettering styles.

**Alphabet of Lines:**
Content: Iba't ibang alphabet of lines; hakbang sa pagguhit ng alphabet of lines.
6. Naiguguhit ang alphabet of lines.

**Orthographic Drawing:**
Content: Orthographic views; hakbang sa pagguhit ng Orthographic Drawing.
7. Nakikilala ang orthographic views.
8. Naisasagawa ang orthographic drawing.

**Isometric Drawing:**
Content: Hakbang sa pagguhit ng Isometric Drawing.
9. Naisasagawa ang pagguhit ng isometric drawing.

**Recycling:**
Content: Kahalagahan ng pagre-recycle; materyales na maaaring i-recycle.
10. Naipaliliwanag ang kahalagahan ng pagre-recycle.

**Pagbuo ng malikhaing proyekto mula sa recyclable materials:**
Content: Hakbang sa pagkalap ng mga materyales; paghahanda ng mga kasangkapan; hakbang sa pagbuo ng proyekto.
11. Nakagagawa ng plano ng proyekto.
12. Nakabubuo ng recycled project/s nang may pag-iingat.
13. Natutuos ang gastos, presyo, at posibleng kita ng nabuong proyekto manually o gamit ang spreadsheet.

