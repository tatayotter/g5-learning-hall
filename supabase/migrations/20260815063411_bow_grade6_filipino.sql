## Unang Markahan (uri ng teksto: epiko/alamat/maikling kuwento; kasanayan: paglalahad ng paksa at suliranin)
- **Pakikinig at Pagbasa:** Pakikinig at pagbasa ng epiko, alamat, at maikling kuwento na may mas kumplikadong balangkas; pagtukoy sa suliranin at tunggalian sa kuwento.
- **Pagsasalita at Pagsulat:** Pagsulat ng buod ng isang binasang akda, kasama ang paksa, tunggalian, at resolusyon; pagbibigay-opinyon tungkol sa isang isyu sa kuwento nang may sapat na dahilan.
- **Panonood at Presentasyon:** Panonood at pagsusuri ng dulaang pinapalabas o klip na hango sa isang epiko o alamat.
- **Gramatika:** Pang-abay na pamanahon at panlunan; wastong paggamit ng mga ito sa pagsulat ng buod.

**Special Science enrichment:** hindi inilalapat sa asignaturang Filipino.

## Ikalawang Markahan (uri ng teksto: tekstong impormatibo/panayam; kasanayan: pananaliksik at pag-uulat)
