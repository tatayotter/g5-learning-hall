- **Pagsasalita at Pagsulat:** Pagsasagawa ng maikling panayam sa isang miyembro ng komunidad; pagsulat ng ulat batay sa nakalap na impormasyon mula sa panayam o pananaliksik.
- **Panonood at Presentasyon:** Pag-uulat nang pasalita ng resulta ng panayam o pananaliksik sa harap ng klase.
- **Gramatika:** Pahayag na patuwid (reported speech); wastong paggamit sa pag-uulat ng sinabi ng kapanayam.

